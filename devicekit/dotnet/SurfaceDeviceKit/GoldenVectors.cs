using System.Text.Json;
using System.Text.Json.Nodes;

namespace SurfaceDeviceKit;

/// <summary>The structural part of every simulated device's answer: classes, lanes, budgets, execution providers, capability statuses and model ladders.
/// It is written to vectors/golden-profiles.json, and the Python port is tested against the same file, so the two cannot drift apart.
/// Free-text strings (details, summaries) are left out on purpose.</summary>
public static class GoldenVectors
{
    private sealed record GLane(string Id, bool Available, double BudgetGb, string ClassCap, IReadOnlyList<string> Eps);
    private sealed record GGpu(string Vendor, string Kind, double VramGb);
    private sealed record GNpu(double? RatedTops, bool LlmCapable);
    private sealed record GCap(string Id, string Status, string Lane);
    private sealed record GPlan(string? PrimaryLane, string? Primary, IReadOnlyDictionary<string, IReadOnlyList<string>> Ladders);
    private sealed record GDevice(
        string DeviceClass, string PcClass, string FamilyId, bool Emulated, int RamTier, double InstalledGb, double VisibleGb,
        IReadOnlyList<GGpu> Gpus, IReadOnlyList<GNpu> Npus, IReadOnlyList<GLane> Lanes, IReadOnlyList<GCap> Capabilities,
        IReadOnlyDictionary<string, GPlan> Plans);
    private sealed record GFile(int Schema, string CatalogVersion, string Note, IReadOnlyDictionary<string, GDevice> Devices);

    /// <summary>Numbers are compared to this many gigabytes: both ports round to two decimals, and half-way cases may land either side.</summary>
    public const double Tolerance = 0.011;

    public static string Build(Catalog? catalog = null)
    {
        catalog ??= Catalog.Default;
        var devices = new Dictionary<string, GDevice>();
        foreach (var sim in SimulatedProfiles.All)
            devices[sim.Id] = Reduce(DeviceDetectionService.Analyze(sim.Raw, catalog, "simulated", sim.Id, sim.Label));
        var file = new GFile(1, catalog.CatalogVersion,
            "Generated by \"surface-device --golden\" from simulated-profiles.json and device-catalog.json. Do not edit by hand; regenerate after changing either file or the classification rules.",
            devices);
        return DeviceJson.Serialize(file);
    }

    private static GDevice Reduce(DeviceReport r)
    {
        var p = r.Profile;
        return new GDevice(
            p.DeviceClass, p.PcClass, p.Cpu.FamilyId, p.Os.Emulated, p.Memory.Tier, p.Memory.InstalledGb, p.Memory.VisibleGb,
            p.Gpus.Select(g => new GGpu(g.Vendor, g.Kind, g.VramGb)).ToList(),
            p.Npus.Select(n => new GNpu(n.RatedTops, n.LlmCapable)).ToList(),
            p.Lanes.Select(l => new GLane(l.Id, l.Available, l.BudgetGb, l.ClassCap, l.Eps)).ToList(),
            p.Capabilities.Select(c => new GCap(c.Id, c.Status, c.Lane)).ToList(),
            r.Plans.ToDictionary(
                kv => kv.Key,
                kv => new GPlan(kv.Value.PrimaryLane, kv.Value.Primary?.Alias,
                    kv.Value.Lanes.ToDictionary(l => l.Lane, l => (IReadOnlyList<string>)l.Ladder.Select(m => m.Alias).ToList()))));
    }

    /// <summary>Paths where the two documents differ. Numbers match within <see cref="Tolerance"/>; everything else must be equal.</summary>
    public static List<string> Compare(string expectedJson, string actualJson)
    {
        var diffs = new List<string>();
        Walk(JsonNode.Parse(expectedJson), JsonNode.Parse(actualJson), "$", diffs);
        return diffs;
    }

    private static void Walk(JsonNode? expected, JsonNode? actual, string path, List<string> diffs)
    {
        if (expected is null || actual is null)
        {
            if (expected is not null || actual is not null) diffs.Add($"{path}: expected {Show(expected)}, got {Show(actual)}");
            return;
        }
        switch (expected)
        {
            case JsonObject eo when actual is JsonObject ao:
                foreach (string key in eo.Select(kv => kv.Key).Union(ao.Select(kv => kv.Key)))
                {
                    eo.TryGetPropertyValue(key, out var e);
                    ao.TryGetPropertyValue(key, out var a);
                    if (!eo.ContainsKey(key)) diffs.Add($"{path}.{key}: unexpected");
                    else if (!ao.ContainsKey(key)) diffs.Add($"{path}.{key}: missing");
                    else Walk(e, a, $"{path}.{key}", diffs);
                }
                break;
            case JsonArray ea when actual is JsonArray aa:
                if (ea.Count != aa.Count) diffs.Add($"{path}: expected {ea.Count} items, got {aa.Count}");
                for (int i = 0; i < Math.Min(ea.Count, aa.Count); i++) Walk(ea[i], aa[i], $"{path}[{i}]", diffs);
                break;
            case JsonValue ev when actual is JsonValue av:
                if (ev.GetValueKind() == JsonValueKind.Number && av.GetValueKind() == JsonValueKind.Number)
                {
                    if (Math.Abs(ev.GetValue<double>() - av.GetValue<double>()) > Tolerance) diffs.Add($"{path}: expected {Show(ev)}, got {Show(av)}");
                }
                else if (ev.ToJsonString() != av.ToJsonString()) diffs.Add($"{path}: expected {Show(ev)}, got {Show(av)}");
                break;
            default:
                diffs.Add($"{path}: the shape differs");
                break;
        }
    }

    private static string Show(JsonNode? n) => n?.ToJsonString() ?? "null";
}
