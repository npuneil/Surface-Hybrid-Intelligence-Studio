#Requires -Version 7.2
<#
.SYNOPSIS
Conformance gate for an edition tree (this repository or one generated by New-Edition.ps1).
.DESCRIPTION
Checks, in order: manifest, generated-file sync, forbidden-token leak scan, hygiene scan (user-profile
paths, credentials, keys), Python tests, native build + self-test + UI smoke (-Live adds CUDA runs) and,
with -Browser, the browser check against a rehearsal-only service (refreshes Executive-Handout.pdf).
Writes .runtime\edition-conformance.json and exits 1 if anything failed.
.EXAMPLE
pwsh tools\Test-Edition.ps1 -Path ..\Surface-Hybrid-Intelligence-Studio -ForbiddenToken <old-brand> -Browser
#>
[CmdletBinding()]
param(
    [string]$Path = (Split-Path $PSScriptRoot -Parent),
    [string[]]$ForbiddenToken = @(),
    [switch]$Live,
    [switch]$Browser,
    [switch]$SkipNative,
    [ValidateRange(1, 65535)][int]$NativePort = 8796,
    [ValidateRange(1, 65535)][int]$BrowserPort = 8797
)
$ErrorActionPreference = 'Stop'
$browserPortExplicit = $PSBoundParameters.ContainsKey('BrowserPort')
$Path = (Resolve-Path -LiteralPath $Path).Path.TrimEnd('\')
Import-Module (Join-Path $Path 'tools\Edition.psm1') -Force
$results = [System.Collections.Generic.List[object]]::new()
$runtime = Join-Path $Path '.runtime'
$null = New-Item -ItemType Directory -Path $runtime -Force

function Step([string]$Name, [scriptblock]$Body) {
    $watch = [System.Diagnostics.Stopwatch]::StartNew()
    Write-Host "== $Name" -ForegroundColor Cyan
    try {
        $detail = & $Body
        $passed = $true
    } catch {
        $detail = $_.Exception.Message
        $passed = $false
    }
    $results.Add([pscustomobject]@{ step = $Name; passed = $passed; detail = "$detail"; seconds = [math]::Round($watch.Elapsed.TotalSeconds, 1) })
    Write-Host ("   {0} {1}" -f $(if ($passed) { 'PASS' } else { 'FAIL' }), $detail) -ForegroundColor $(if ($passed) { 'Green' } else { 'Red' })
}

function Find-Python {
    $configured = [Environment]::GetEnvironmentVariable($edition.envPrefix + 'PYTHON')
    $candidates = @($configured, (Join-Path $Path '.venv\Scripts\python.exe'), (Get-Command python -ErrorAction SilentlyContinue).Source)
    $found = $candidates | Where-Object { $_ -and (Test-Path -LiteralPath $_) } | Select-Object -First 1
    if (-not $found) { throw "No Python found. Set $($edition.envPrefix)PYTHON or create .venv." }
    return $found
}

$edition = $null
Step 'manifest' {
    $script:edition = Read-Edition -Path (Join-Path $Path 'edition.json')
    $targets = @(Get-ChildItem -LiteralPath (Join-Path $Path 'editions') -Filter '*.json' -File -ErrorAction SilentlyContinue)
    foreach ($file in $targets) {
        $target = Read-Edition -Path $file.FullName -Target
        if ($target.id -ne $file.BaseName) { throw "editions\$($file.Name) has id '$($target.id)'; the file name and id must match." }
        $null = Get-EditionIdentityMap -From $edition -To $target
    }
    $suffix = if ($targets.Count) { "; targets valid: $(($targets.BaseName) -join ', ')" } else { '' }
    "$($edition.id): $($edition.displayName) ($($edition.visibility) -> $($edition.repository))$suffix"
}
if (-not $edition) { $edition = Get-Content -LiteralPath (Join-Path $Path 'edition.json') -Raw | ConvertFrom-Json }

Step 'sync' {
    $drift = @(Sync-EditionTree -Root $Path -Check)
    if ($drift.Count) { throw "Out of date: $($drift -join ', '). Run tools\Sync-Edition.ps1." }
    'Brand.cs, logo, icon and accents match edition.json'
}

$files = Get-EditionFiles -Root $Path
Step 'leak-scan' {
    if (-not $ForbiddenToken) { return 'skipped (no -ForbiddenToken given)' }
    $hits = @(Find-EditionLeaks -Root $Path -Token $ForbiddenToken -Files $files)
    if ($hits.Count) { throw (($hits | Select-Object -First 15 | ForEach-Object { "'$($_.Token)' in $($_.File) ($($_.Where))" }) -join '; ') }
    "$($files.Count) files clean of: $($ForbiddenToken -join ', ')"
}

Step 'hygiene-scan' {
    $issues = @(Find-HygieneIssues -Root $Path -Files $files)
    if ($issues.Count) { throw (($issues | Select-Object -First 15 | ForEach-Object { "$($_.Issue) in $($_.File) ($($_.Where))" }) -join '; ') }
    "$($files.Count) files: no user-profile paths, tokens or keys"
}

Step 'python-tests' {
    $python = Find-Python
    Push-Location -LiteralPath $Path
    try { $output = & $python -m unittest discover -s tests 2>&1 | Out-String } finally { Pop-Location }
    $summary = ($output -split "`r?`n" | Where-Object { $_ -match '^(Ran \d+ tests|OK|FAILED)' }) -join ' '
    if ($LASTEXITCODE -ne 0) { throw "$summary`n$($output.Substring([Math]::Max(0, $output.Length - 3000)))" }
    $summary
}

if (-not $SkipNative) {
    Step 'native' {
        $arguments = @('-NoProfile', '-File', (Join-Path $Path 'tests\Native-Smoke.ps1'), '-Rebuild', '-Port', $NativePort)
        if ($Live) { $arguments += '-Live' }
        $output = & pwsh @arguments 2>&1 | Out-String
        $code = $LASTEXITCODE
        $self = Get-Content -LiteralPath (Join-Path $runtime 'native\self-test.json') -Raw | ConvertFrom-Json
        $smoke = Get-Content -LiteralPath (Join-Path $runtime 'native\native-smoke.json') -Raw | ConvertFrom-Json
        $passedChecks = @($smoke.checks | Where-Object passed).Count
        $summary = "self-test $($self.total - $self.failed)/$($self.total); UI smoke $passedChecks/$(@($smoke.checks).Count) (live=$($smoke.live_inference_checked))"
        if ($code -ne 0) { throw "$summary`n$($output.Substring([Math]::Max(0, $output.Length - 3000)))" }
        $summary
    }
}

if ($Browser) {
    Step 'browser' {
        $python = Find-Python
        $log = Join-Path $runtime 'edition-browser-server.log'
        $busy = Get-NetTCPConnection -State Listen -LocalPort $BrowserPort -ErrorAction SilentlyContinue | Select-Object -First 1
        if ($busy) {
            if ($browserPortExplicit) { throw "Port $BrowserPort is already in use (PID $($busy.OwningProcess)); pass a free -BrowserPort." }
            $probe = [System.Net.Sockets.TcpListener]::new([System.Net.IPAddress]::Loopback, 0)
            $probe.Start(); $BrowserPort = $probe.LocalEndpoint.Port; $probe.Stop()
        }
        $server = Start-Process -FilePath $python -ArgumentList @('server.py', '--port', $BrowserPort, '--rehearsal-only') -WorkingDirectory $Path `
            -RedirectStandardError $log -RedirectStandardOutput "$log.out" -PassThru -WindowStyle Hidden
        try {
            $deadline = (Get-Date).AddSeconds(90)
            $status = $null
            while (-not $status -and (Get-Date) -lt $deadline) {
                if ($server.HasExited) { throw "server.py exited ($($server.ExitCode)); see $log" }
                try { $status = Invoke-RestMethod "http://127.0.0.1:$BrowserPort/api/status" -TimeoutSec 2 } catch { Start-Sleep -Milliseconds 500 }
            }
            if (-not $status) { throw 'Rehearsal service did not start.' }
            if ($status.app_id -ne $edition.serviceAppId) { throw "Port $BrowserPort answered as '$($status.app_id)', not this edition." }
            $output = & pwsh -NoProfile -File (Join-Path $Path 'tests\Browser-Smoke.ps1') -BaseUrl "http://127.0.0.1:$BrowserPort" 2>&1 | Out-String
            if ($LASTEXITCODE -ne 0) { throw $output.Substring([Math]::Max(0, $output.Length - 3000)) }
            $report = Get-Content -LiteralPath (Join-Path $runtime 'browser-checks.json') -Raw | ConvertFrom-Json
            Copy-Item -LiteralPath (Join-Path $runtime 'Executive-Handout.pdf') -Destination (Join-Path $Path 'Executive-Handout.pdf') -Force
            "$(@($report.checks).Count) browser checks; Executive-Handout.pdf refreshed"
        } finally {
            if (-not $server.HasExited) { Stop-Process -Id $server.Id -Force }
        }
    }
    if (Test-Path -LiteralPath (Join-Path $Path 'Executive-Handout.pdf')) {
        Step 'handout-scan' {
            $issues = @(Find-HygieneIssues -Root $Path -Files @('Executive-Handout.pdf'))
            if ($issues.Count) { throw "Executive-Handout.pdf contains: $(($issues.Issue | Sort-Object -Unique) -join ', ')" }
            if ($ForbiddenToken) {
                $hits = @(Find-EditionLeaks -Root $Path -Token $ForbiddenToken -Files @('Executive-Handout.pdf'))
                if ($hits.Count) { throw "Executive-Handout.pdf contains: $(($hits.Token | Sort-Object -Unique) -join ', ')" }
            }
            "Executive-Handout.pdf clean (hygiene$(if ($ForbiddenToken) { ' + forbidden tokens' }))"
        }
    }
}

$failed = @($results | Where-Object { -not $_.passed })
[ordered]@{
    schema = 'studio-edition-conformance/1'
    edition = $edition.id
    display_name = $edition.displayName
    checked_at = (Get-Date).ToString('o')
    forbidden_tokens = $ForbiddenToken
    live = [bool]$Live
    browser = [bool]$Browser
    passed = $failed.Count -eq 0
    steps = $results
} | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath (Join-Path $runtime 'edition-conformance.json') -Encoding utf8

Write-Host ''
Write-Host ("Edition conformance: {0}/{1} steps passed -> {2}" -f ($results.Count - $failed.Count), $results.Count, (Join-Path $runtime 'edition-conformance.json')) `
    -ForegroundColor $(if ($failed.Count) { 'Red' } else { 'Green' })
if ($failed.Count) { exit 1 }
