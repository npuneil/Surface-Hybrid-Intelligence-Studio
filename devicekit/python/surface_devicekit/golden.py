"""The structural part of every simulated device's answer: classes, lanes, budgets, execution providers, capability statuses and model ladders.
It is written to vectors/golden-profiles.json, and both ports are tested against that file, so the two cannot drift apart.
Free-text strings (details, summaries) are left out on purpose."""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass
from typing import Any

from .catalog import Catalog
from .dotnet import escape_string
from .jsonio import RawNumber, dumps, loads, to_json
from .models import DeviceReport, SimulatedDevice
from .service import analyze
from .simulate import all_devices

# Both ports round to two decimals, and half-way cases may land either side, so numbers are compared to this many gigabytes.
TOLERANCE = 0.011

NOTE = (
    'Generated by "surface-device --golden" from simulated-profiles.json and device-catalog.json. '
    "Do not edit by hand; regenerate after changing either file or the classification rules."
)


@dataclass(frozen=True, slots=True)
class GoldenLane:
    id: str
    available: bool
    budget_gb: float
    class_cap: str
    eps: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class GoldenGpu:
    vendor: str
    kind: str
    vram_gb: float


@dataclass(frozen=True, slots=True)
class GoldenNpu:
    rated_tops: float | None
    llm_capable: bool


@dataclass(frozen=True, slots=True)
class GoldenCapability:
    id: str
    status: str
    lane: str


@dataclass(frozen=True, slots=True)
class GoldenPlan:
    primary_lane: str | None
    primary: str | None
    ladders: dict[str, tuple[str, ...]]


@dataclass(frozen=True, slots=True)
class GoldenDevice:
    device_class: str
    pc_class: str
    family_id: str
    emulated: bool
    ram_tier: int
    installed_gb: float
    visible_gb: float
    gpus: tuple[GoldenGpu, ...]
    npus: tuple[GoldenNpu, ...]
    lanes: tuple[GoldenLane, ...]
    capabilities: tuple[GoldenCapability, ...]
    plans: dict[str, GoldenPlan]


@dataclass(frozen=True, slots=True)
class GoldenFile:
    schema: int
    catalog_version: str
    note: str
    devices: dict[str, GoldenDevice]


def reduce(report: DeviceReport) -> GoldenDevice:
    p = report.profile
    return GoldenDevice(
        p.device_class,
        p.pc_class,
        p.cpu.family_id,
        p.os.emulated,
        p.memory.tier,
        p.memory.installed_gb,
        p.memory.visible_gb,
        tuple(GoldenGpu(g.vendor, g.kind, g.vram_gb) for g in p.gpus),
        tuple(GoldenNpu(n.rated_tops, n.llm_capable) for n in p.npus),
        tuple(GoldenLane(lane.id, lane.available, lane.budget_gb, lane.class_cap, lane.eps) for lane in p.lanes),
        tuple(GoldenCapability(c.id, c.status, c.lane) for c in p.capabilities),
        {
            workload_id: GoldenPlan(
                plan.primary_lane,
                plan.primary.alias if plan.primary is not None else None,
                {lane.lane: tuple(m.alias for m in lane.ladder) for lane in plan.lanes},
            )
            for workload_id, plan in report.plans.items()
        },
    )


def build(catalog: Catalog | None = None, devices: Iterable[SimulatedDevice] | None = None) -> str:
    """The golden-vectors document for every simulated device, as JSON text."""
    if catalog is None:
        catalog = Catalog.default()
    pool = all_devices() if devices is None else devices
    reduced = {d.id: reduce(analyze(d.raw, catalog, "simulated", d.id, d.label)) for d in pool}
    return to_json(GoldenFile(1, catalog.catalog_version, NOTE, reduced))


def compare(expected_json: str, actual_json: str) -> list[str]:
    """Paths where the two documents differ. Numbers match within TOLERANCE; everything else must be equal."""
    diffs: list[str] = []
    _walk(loads(expected_json, comments=False, keep_numbers=True), loads(actual_json, comments=False, keep_numbers=True), "$", diffs)
    return diffs


def _show(node: Any) -> str:
    if node is None:
        return "null"
    if isinstance(node, str):
        return escape_string(node)
    return dumps(node, indented=False)


def _walk(expected: Any, actual: Any, path: str, diffs: list[str]) -> None:
    if expected is None or actual is None:
        if expected is not None or actual is not None:
            diffs.append(f"{path}: expected {_show(expected)}, got {_show(actual)}")
    elif isinstance(expected, dict) and isinstance(actual, dict):
        for key in [*expected, *(k for k in actual if k not in expected)]:
            if key not in expected:
                diffs.append(f"{path}.{key}: unexpected")
            elif key not in actual:
                diffs.append(f"{path}.{key}: missing")
            else:
                _walk(expected[key], actual[key], f"{path}.{key}", diffs)
    elif isinstance(expected, list) and isinstance(actual, list):
        if len(expected) != len(actual):
            diffs.append(f"{path}: expected {len(expected)} items, got {len(actual)}")
        for i, (e, a) in enumerate(zip(expected, actual)):
            _walk(e, a, f"{path}[{i}]", diffs)
    elif not isinstance(expected, (dict, list)) and not isinstance(actual, (dict, list)):
        if isinstance(expected, RawNumber) and isinstance(actual, RawNumber):
            different = abs(float(expected) - float(actual)) > TOLERANCE
        else:
            different = _show(expected) != _show(actual)
        if different:
            diffs.append(f"{path}: expected {_show(expected)}, got {_show(actual)}")
    else:
        diffs.append(f"{path}: the shape differs")
